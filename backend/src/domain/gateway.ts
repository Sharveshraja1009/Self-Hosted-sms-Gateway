/**
 * Gateways - the Android phones that actually push SMS through a SIM.
 *
 * A Gateway row is the *persistent* record of a device: it survives restarts and
 * exists whether or not the phone is currently plugged in. The live WebSocket is
 * a separate, in-memory thing (see gateway.registry.ts). Conflating the two is a
 * classic mistake: you end up unable to answer "which of my devices exist?" from
 * anywhere but the one process that happens to hold the socket, and the moment
 * you run two replicas the dashboard starts lying.
 */

export const GatewayStatus = {
  /** Registered, but no live WebSocket. */
  OFFLINE: 'OFFLINE',
  /** Connected and heartbeating. Eligible to receive messages. */
  ONLINE: 'ONLINE',
  /** Connected but unhealthy - no SIM, permissions revoked, radio off. */
  DEGRADED: 'DEGRADED',
  /** Administratively disabled. Never dispatched to. */
  DISABLED: 'DISABLED',
} as const;

export type GatewayStatus = (typeof GatewayStatus)[keyof typeof GatewayStatus];

/**
 * Telemetry the phone reports on every heartbeat.
 *
 * Every field is nullable, and that is deliberate: `null` means "the device did
 * not tell us", which is a genuinely different state from "0%". A sentinel like
 * -1 for unknown battery would eventually get rendered in the dashboard as
 * "-1%", or worse, compared with `< 20` and trigger a low-battery alert on a
 * device that simply has not reported yet.
 */
/**
 * One SIM inside a handset.
 *
 * This is the unit the send path actually cares about. A gateway is a *phone*; a
 * SimLine is a *number*. A dual-SIM phone is one gateway with two lines, and the
 * distinction matters because the daily quota, the routing, and the "from" on
 * every message all belong to the line, not the handset.
 */
export interface SimLine {
  /**
   * Android's own handle for this SIM. The only reliable identity: it survives a
   * relabel, and it is what `SmsManager.createForSubscriptionId()` needs.
   */
  subscriptionId: number;
  /** 1 or 2, matching what the phone's Settings screen shows the operator. */
  slot: number;
  carrier: string | null;
  /**
   * The number, as typed in by a human.
   *
   * Null until someone labels it. NOT VERIFIED - Android will not tell us the
   * real number, so this is a label the device asserted. Never treat it as proof
   * of identity; it is how the send API addresses a line, and how a person
   * recognises it.
   */
  phoneNumber: string | null;
}

export interface DeviceTelemetry {
  batteryLevel: number | null;
  isCharging: boolean | null;
  simOperator: string | null;
  phoneNumber: string | null;
  androidVersion: string | null;
  appVersion: string | null;
  /** False when SEND_SMS is not granted or no SIM is present - the device cannot send. */
  canSendSms: boolean | null;
  /**
   * Every SIM in this handset.
   *
   * Empty for an old APK that predates multi-SIM support, which is exactly why
   * the dispatcher falls back to `phoneNumber` and subscriptionId -1 when this is
   * empty - a phone in a drawer running last month's build must keep working.
   */
  sims: SimLine[];
}

export interface Gateway extends DeviceTelemetry {
  id: string;
  /** Stable per-install identifier generated by the Android app. */
  deviceId: string;
  deviceName: string;
  userId: string;

  status: GatewayStatus;

  lastSeenAt: Date | null;
  lastConnectedAt: Date | null;
  createdAt: Date;
  updatedAt: Date;
}

export interface PublicGateway extends DeviceTelemetry {
  id: string;
  deviceId: string;
  deviceName: string;
  status: GatewayStatus;
  lastSeenAt: string | null;
  lastConnectedAt: string | null;
  createdAt: string;
}

export function toPublicGateway(gateway: Gateway): PublicGateway {
  return {
    id: gateway.id,
    deviceId: gateway.deviceId,
    deviceName: gateway.deviceName,
    status: gateway.status,
    batteryLevel: gateway.batteryLevel,
    isCharging: gateway.isCharging,
    simOperator: gateway.simOperator,
    phoneNumber: gateway.phoneNumber,
    androidVersion: gateway.androidVersion,
    appVersion: gateway.appVersion,
    canSendSms: gateway.canSendSms,
    sims: gateway.sims,
    lastSeenAt: gateway.lastSeenAt?.toISOString() ?? null,
    lastConnectedAt: gateway.lastConnectedAt?.toISOString() ?? null,
    createdAt: gateway.createdAt.toISOString(),
  };
}

/** Can this device be handed a message right now? */
export function isDispatchable(gateway: Gateway): boolean {
  return gateway.status === GatewayStatus.ONLINE && gateway.canSendSms !== false;
}

/**
 * The lines this gateway can actually send from.
 *
 * Falls back to a single synthetic line when the device reported no `sims` array
 * - which is what an APK predating multi-SIM support does. That phone still works;
 * it just has exactly one line, sending from Android's default subscription (-1).
 * Without this fallback, upgrading the server would silently stop every old handset
 * from sending, and the failure would look like "no SIM available" rather than
 * "your app is old".
 */
export function linesOf(gateway: Gateway): SimLine[] {
  if (gateway.sims.length > 0) return gateway.sims;

  return [
    {
      subscriptionId: -1,
      slot: 1,
      carrier: gateway.simOperator,
      phoneNumber: gateway.phoneNumber,
    },
  ];
}
